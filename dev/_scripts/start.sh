#!/bin/bash

# A Simple Shell Script To get a new Craft Project up and running
# 2019 (c) kreisvier Communications AG (Mischa Sprecher)
#
# Version 2.5 with photoswipe npm support
#
# HINWEIS: Script setzt git zurück, wenn in /dev ein file ".k4-git-init" gefunden wird.

tput setaf 4;printf "\n\n### WELCOME TO k4 Craft Project Installation ###\n\n"


tput setaf 5;printf "\n### git Settings \n"


if [ -f "dev/.k4-git-init" ]; then
        tput setaf 6;printf "\n  √  Neue git Settings anlegen\n"
        tput setaf 2;

        tput setaf 6;printf "  √  .gitignore anpassen\n"
        tput setaf 2;

        sed -i -e 's/#vendor/vendor/' '.gitignore'
        sed -i -e 's/#composer.lock/composer.lock/' '.gitignore'

        tput setaf 6;printf "  √  entferne .git Ordner\n"
        tput setaf 2;
        rm -rf .git

        tput setaf 6;printf "  √  Lokales git repository initialisieren\n\n"
        tput setaf 2;

        git init

        rm "dev/.k4-git-init"
else

        tput setaf 6;printf "\n  √  Bestehende git Settings werden beibehalten\n"     

fi

tput setaf 5;printf "\n### Composer updates\n"
tput setaf 6;


wait

composer update --no-suggest --quiet

wait

if [ $? -eq 0 ]; then
    tput setaf 6;printf "\n  √ Composer updates OK.\n"
else
    tput setaf 1;printf "\n  x Fehler beim Composer update Prozess";
fi

# Check for env file and generate one if missing

tput setaf 5;printf "\n### .env File\n"
tput setaf 6;

if [ -f ".env default" ]&& [ ! -f ".env" ]; then
    cp ".env default" ".env"
    tput setaf 6;printf "\n  √ .env kopiert von .env default\n"
elif [ -f ".env.example" ] && [ ! -f ".env" ]; then
    cp ".env.example" ".env"
    tput setaf 6;printf "\n  √ .env kopiert von .env.example\n"
else
    if [ ! -f ".env" ]; then
        tput setaf 1;printf "\n  x Kein default .env gefunden: Generiere neues .env file!\n"
        cat > .env <<EOF
        # .env file generated by k4 Communications AG
        ENVIRONMENT="dev"
        SECURITY_KEY=""
        DB_DRIVER="mysql"
        DB_SERVER="127.0.0.1"
        DB_USER="root"
        DB_PASSWORD=""
        DB_DATABASE=""
        DB_SCHEMA="public"
        DB_TABLE_PREFIX="k4_"
        DB_PORT="3306"
        DEFAULT_SITE_URL="https://your-project.localhost"
EOF
    else
        tput setaf 6;printf "\n  √ Bestehendes .env File gefunden\n"
    fi
fi

tput setaf 6;

wait

chmod +x ./craft


# CREATE CRAFT CMS SECURITY KEY IF NONE FOUND

if grep -q "SECURITY_KEY=\"\"" ".env"; then
    tput setaf 5;printf "\n### Craft CMS Security-Key"
    tput setaf 6;
    ./craft setup/security-key
    tput setaf 6;printf "  √ Craft CMS Security-Key geschrieben.\n"
else
    tput setaf 6;printf "\n  √ Bestehenden Craft CMS Security Key gefunden\n";
fi


# NODE MODULES

tput setaf 5;printf "\n### Installiere Node Modules\n"
tput setaf 6;

npm --quiet install

wait 

tput setaf 5;printf "### Versuche fix von möglichen NPM vulnerabilities\n"
tput setaf 6;

npm audit fix

wait 

tput setaf 5;printf "\n### Kopiere NPM Vendor Daten nach /dev\n"


# erstellt Vendor Ordner in SASS 
mkdir -p dev/_SASS/_vendors/libs

tput setaf 6;printf "\n  √ Verzeichnis erstellt (dev/_SASS/_vendors/libs)"
sleep 1

# Copy bourbon assets from node_modules to vendor folder
cp -R node_modules/bourbon/core/ dev/_SASS/_vendors/bourbon

tput setaf 6;printf "\n  √ Bourbon kopiert (dev/_SASS/_vendors/bourbon)"
sleep 1

# Copy bourbon core from node_modules to vendor folder
cp -R node_modules/bourbon-neat/core dev/_SASS/_vendors/neat

tput setaf 6;printf "\n  √ Neat kopiert (dev/_SASS/_vendors/neat)"
sleep 1

# Copy photoswipe from node_modules to vendor folder
cp -R node_modules/photoswipe/src dev/_SASS/_vendors/photoswipe

tput setaf 6;printf "\n  √ PhotoSwipe kopiert (dev/_SASS/_vendors/photoswipe)"
sleep 1

# Copy Normalize.scss to vendor folder 
cp -R node_modules/normalize-scss/sass/ dev/_SASS/_vendors/libs

tput setaf 6;printf "\n  √ Normalize SASS kopiert (dev/_SASS/_vendors/libs)\n"
sleep 1

# public or web ?

tput setaf 5;printf "\n\n### Web root Verzeichnis\n"
tput setaf 2;

if [ -d "public" ]; then
  WEBDIR='public'
elif [ -d "web" ]; then
  WEBDIR='web'
else
  mkdir -p public/tpl/js/libs
  WEBDIR='public'
  tput setaf 6;printf "  √ Das Verzeichnis \'public/tpl/js/libs\' wurde neu erstellt\n";tput setaf 2;
fi

# Check if subdirectory exists
if [ -d "$WEBDIR/tpl/js/libs" ]; then
  DIRECTORY=$WEBDIR'/tpl/js/libs'
elif [ -d "$WEBDIR/assets/js/libs" ]; then
  DIRECTORY=$WEBDIR'/assets/js/libs'
else
    if [ -d "$WEBDIR/tpl/" ]; then
        mkdir -p $WEBDIR/tpl/js/libs
        DIRECTORY=$WEBDIR'/tpl/js/libs'
    elif [ -d "$WEBDIR/assets/" ]; then
        mkdir -p $WEBDIR/assets/js/libs
        DIRECTORY=$WEBDIR'/assets/js/libs'
    fi
fi


# Copy jQuery libary to public assets folder
[ -f "node_modules/jquery/dist/jquery.min.js" ] && cp "node_modules/jquery/dist/jquery.min.js" "$DIRECTORY"

if [ $? -eq 0 ]; then
    tput setaf 6;printf "\n  √ \jQuery libary nach \'$DIRECTORY\' kopiert\n"
else
    tput setaf 1;printf "\n  x Fehler beim Kopieren der jQuery Library!";
fi

# Copy photoswipe libary to public assets folder
#[ -f "node_modules/photoswipe/dist/photoswipe.min.js" ] && cp "node_modules/photoswipe/dist/photoswipe.min.js" "$DIRECTORY"
#[ -f "node_modules/photoswipe/dist/photoswipe-ui-default.min.js" ] && cp "node_modules/photoswipe/dist/photoswipe-ui-default.min.js" "$DIRECTORY"

cp -r "node_modules/photoswipe/dist/" "$DIRECTORY"

if [ $? -eq 0 ]; then
    tput setaf 6;printf "\n  √ \jQuery libary nach \'$DIRECTORY\' kopiert\n"
else
    tput setaf 1;printf "\n  x Fehler beim Kopieren der photoSwipe Library!";
fi

tput setaf 5;printf "\n\n### Cleaning up...\n"

if [ -f ".gitignore-e" ]; then
    rm '.gitignore-e'
fi

if [ -f ".env default" ]; then
    rm ".env default"
elif [ -f ".env.example" ]; then
    rm ".env.example"
fi

tput setaf 2;printf "\n\n! ";tput setaf 4;printf "! ";tput setaf 6;printf "! ";tput setaf 5;tput bold;printf "H a p p y   C o d i n g ";tput setaf 2;printf "! ";tput setaf 4;printf "! ";tput setaf 6;printf "!\n\n\n"
echo  -e "\033[33;5m### May the force be with you ###\033[0m\n\n"

tput sgr0;