import assert from 'node:assert/strict';
import navigation from '../src/js/components/navigation.js';
import codeCopy from '../src/js/components/codeCopy.js';
const main = {inert: false};
const footer = {inert: false};
const classes = new Set();
globalThis.document = {
    documentElement: {classList: {toggle(name, enabled) {enabled ? classes.add(name) : classes.delete(name);}}},
    querySelectorAll: () => [main, footer],
};
let focused = '';
const first = {getClientRects: () => [1], focus() {focused = 'first';}};
const last = {getClientRects: () => [1], focus() {focused = 'last';}};
const nav = navigation();
nav.$nextTick = callback => callback();
nav.$refs = {panel: {querySelector: () => first}, toggle: {focus() {focused = 'toggle';}}};
nav.$el = {querySelectorAll: () => [first, last]};
nav.toggle();
assert.equal(nav.open, true);
assert.equal(focused, 'first');
assert.equal(main.inert, true);
assert.equal(footer.inert, true);
assert.equal(classes.has('mobile-menu-open'), true);
let prevented = false;
document.activeElement = last;
nav.trapFocus({key: 'Tab', shiftKey: false, preventDefault() {prevented = true;}});
assert.equal(prevented, true);
assert.equal(focused, 'first');
document.activeElement = first;
nav.trapFocus({key: 'Tab', shiftKey: true, preventDefault() {}});
assert.equal(focused, 'last');
nav.toggle();
assert.equal(nav.open, false);
assert.equal(focused, 'toggle');
assert.equal(main.inert, false);
assert.equal(classes.has('mobile-menu-open'), false);
globalThis.matchMedia = () => ({ matches: true });
nav.toggle();
nav.onResize();
assert.equal(nav.open, false);
assert.equal(footer.inert, false);
const content = '  <script>\nconst value = 42;\n';
let copied;
Object.defineProperty(globalThis, 'navigator', {value: {clipboard: {writeText: async value => {copied = value;}}}, configurable: true});
const component = codeCopy();
component.$refs = {code: {textContent: content}};
await component.copy();
assert.equal(copied, content);
assert.equal(component.label, 'Copied');
component.destroy();
let selected = false;
globalThis.navigator.clipboard.writeText = async () => {throw new Error('Denied');};
globalThis.window = {getSelection: () => ({removeAllRanges() {}, addRange() {selected = true;}})};
globalThis.document = {createRange: () => ({selectNodeContents(node) {assert.equal(node.textContent, content);}})};
await component.copy();
assert.equal(component.label, 'Select code');
assert.equal(selected, true);
component.destroy();
console.log('PASS overlay toggle, scroll locking, focus trap/restore, resize cleanup, and clipboard behavior');
